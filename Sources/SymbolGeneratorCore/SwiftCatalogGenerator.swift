import Foundation

public enum SwiftCatalogGenerator {
    /// Generator planning data; the library exposes only the resulting static properties.
    public struct CompatibilityAlias: Equatable, Sendable {
        public let symbolName: String
        public let identifier: String
        public let iOS: OSVersion
        public let macOS: OSVersion
    }

    /// An injective mapping: plain ASCII names, numeric names, and escaped names
    /// occupy separate namespaces. Adding a sibling never renames an existing API.
    public static func identifier(for component: String) -> String {
        let bytes = Array(component.utf8)
        let reserved: Set<String> = ["name", "hash", "hashValue", "init", "self", "Self", "Type", "Protocol"]
        let isLetter: (UInt8) -> Bool = { (65...90).contains($0) || (97...122).contains($0) }
        let isDigit: (UInt8) -> Bool = { (48...57).contains($0) }
        let isTail: (UInt8) -> Bool = { isLetter($0) || isDigit($0) || $0 == 95 }
        if let first = bytes.first, bytes.allSatisfy(isTail) {
            if isLetter(first) && !reserved.contains(component) { return component }
            if isDigit(first) { return "_" + component }
        }
        return "_u" + bytes.map { String(format: "%02x", $0) }.joined()
    }

    public static func generate(catalog: Catalog) -> String {
        let root = makeTree(catalog: catalog)
        var lines = [
            "// Generated by GenerateSymbols. Do not edit.",
            "// \(catalog.entries.count) symbol names from local name_availability.plist metadata.",
            "// Only names and availability are emitted; no Apple artwork or resource files.",
            "",
            "public extension SymbolValue where Self == Symbol {"
        ]
        for child in root.sortedChildren {
            emitProperty(child, static: true, indentation: "    ", root: true, into: &lines)
        }
        lines += ["}", "", "extension Symbol {"]
        for child in root.sortedChildren where !child.children.isEmpty {
            emitBranch(child, indentation: "    ", into: &lines)
        }
        lines += ["}", ""]

        let aliases = compatibilityAliases(root: root)
        if !aliases.isEmpty {
            lines += [
                "// Direct aliases preserve native availability when an ancestor is newer.",
                "// \(aliases.count) aliases; the hierarchical API above is unchanged.",
                "public extension SymbolValue where Self == Symbol {"
            ]
            for alias in aliases {
                lines.append("    " + Availability(iOS: alias.iOS, macOS: alias.macOS).annotation)
                lines.append("    static var `\(alias.identifier)`: Symbol { .init(name: \(literal(alias.symbolName))) }")
            }
            lines += ["}", ""]
        }
        return lines.joined(separator: "\n")
    }

    /// Lists exactly those symbols whose hierarchy requires a newer supported OS.
    public static func compatibilityAliases(catalog: Catalog) -> [CompatibilityAlias] {
        compatibilityAliases(root: makeTree(catalog: catalog))
    }

    private static func makeTree(catalog: Catalog) -> Node {
        let root = Node(component: "", name: "")
        for entry in catalog.entries {
            var current = root
            for component in entry.name.split(separator: ".").map(String.init) {
                if current.children[component] == nil {
                    let name = current.name.isEmpty ? component : current.name + "." + component
                    current.children[component] = Node(component: component, name: name)
                }
                current = current.children[component]!
            }
            current.entry = entry
        }
        setAvailability(root, inherited: baseline)
        return root
    }

    private static var baseline: Availability {
        Availability(iOS: try! OSVersion("13.0"), macOS: try! OSVersion("11.0"))
    }

    private static func compatibilityAliases(root: Node) -> [CompatibilityAlias] {
        let floor = baseline
        var affected: [Node] = []
        func collect(_ node: Node) {
            if let entry = node.entry,
               node.availability.iOS > max(floor.iOS, entry.iOS)
                || node.availability.macOS > max(floor.macOS, entry.macOS) {
                affected.append(node)
            }
            for child in node.sortedChildren { collect(child) }
        }
        collect(root)
        affected.sort { $0.name < $1.name }
        let naturalNames = affected.map { node in
            node.name.split(separator: ".").map { identifier(for: String($0)) }.joined(separator: "_")
        }
        let roots = Set(root.sortedChildren.map { identifier(for: $0.component) })
        let counts = Dictionary(grouping: naturalNames, by: { $0 }).mapValues(\.count)
        // Reserve every natural spelling before assigning suffixes, so resolving
        // one collision cannot steal another alias's otherwise unambiguous name.
        var reserved = roots.union(naturalNames)
        return zip(affected, naturalNames).map { node, natural in
            var name = natural
            if roots.contains(natural) || counts[natural, default: 0] > 1 {
                let suffix = node.name.utf8.map { String(format: "%02x", $0) }.joined()
                let candidate = natural + "_u" + suffix
                name = candidate
                var counter = 2
                while reserved.contains(name) {
                    name = candidate + "_" + String(counter)
                    counter += 1
                }
                reserved.insert(name)
            }
            let entry = node.entry!
            return CompatibilityAlias(
                symbolName: node.name,
                identifier: name,
                iOS: max(floor.iOS, entry.iOS),
                macOS: max(floor.macOS, entry.macOS)
            )
        }
    }

    private struct Availability {
        let iOS: OSVersion
        let macOS: OSVersion
        var annotation: String { "@available(iOS \(iOS), macOS \(macOS), *)" }
    }

    private final class Node {
        let component: String
        let name: String
        var entry: CatalogEntry?
        var children: [String: Node] = [:]
        var availability: Availability!
        init(component: String, name: String) { self.component = component; self.name = name }
        var sortedChildren: [Node] { children.keys.sorted().map { children[$0]! } }
        var typeName: String { "_Branch_" + identifier(for: component) }
    }

    private static func setAvailability(_ node: Node, inherited: Availability) {
        if let entry = node.entry {
            node.availability = Availability(iOS: max(inherited.iOS, entry.iOS), macOS: max(inherited.macOS, entry.macOS))
        } else {
            node.availability = inherited
        }
        for child in node.sortedChildren { setAvailability(child, inherited: node.availability) }
    }

    private static func emitProperty(_ node: Node, static isStatic: Bool, indentation: String, root: Bool, into lines: inout [String]) {
        let type = node.children.isEmpty ? "Symbol" : (root ? "Symbol." : "") + node.typeName
        let value = node.children.isEmpty ? ".init(name: \(literal(node.name)))" : ".init()"
        lines.append(indentation + node.availability.annotation)
        // Backticks are legal for ordinary names and also cover current/future Swift keywords.
        let prefix = isStatic ? "static " : "public "
        lines.append(indentation + prefix + "var `\(identifier(for: node.component))`: \(type) { \(value) }")
    }

    private static func emitBranch(_ node: Node, indentation: String, into lines: inout [String]) {
        lines.append(indentation + node.availability.annotation)
        let conformance = node.entry == nil ? "Hashable, Sendable" : "SymbolValue"
        lines.append(indentation + "public struct \(node.typeName): \(conformance) {")
        let inner = indentation + "    "
        lines.append(inner + "internal init() {}")
        if node.entry != nil { lines.append(inner + "public var name: String { \(literal(node.name)) }") }
        for child in node.sortedChildren {
            emitProperty(child, static: false, indentation: inner, root: false, into: &lines)
        }
        for child in node.sortedChildren where !child.children.isEmpty {
            emitBranch(child, indentation: inner, into: &lines)
        }
        lines.append(indentation + "}")
    }

    private static func literal(_ value: String) -> String {
        "\"" + value.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }
}
